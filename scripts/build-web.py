#!/usr/bin/env python3
"""Compile the HTTP Boot console into one installable Python asset module."""

import hashlib, os, re, subprocess, tempfile
from pathlib import Path

import runpy

# Shared login markup is generated only from the pinned Core template.
runpy.run_path(
    str(Path(__file__).with_name("build-login.py")), run_name="core_login_build"
)

root = Path(__file__).resolve().parents[1]
source = root / "web"
assets = {}
names = {}
scratch = root / ".build-web"
scratch.mkdir(exist_ok=True)
with tempfile.TemporaryDirectory(prefix="httpboot-web-", dir=scratch) as folder:
    for file in sorted(source.iterdir()):
        if file.suffix not in (".css", ".js", ".svg"):
            continue
        if file.suffix == ".svg":
            data = file.read_bytes()
            mime = "image/svg+xml"
        else:
            out = Path(folder) / file.name
            subprocess.run(
                [
                    os.environ.get("ESBUILD", "esbuild"),
                    str(file),
                    "--minify",
                    "--target=es2020",
                    "--charset=utf8",
                    "--legal-comments=inline",
                    "--banner:"
                    + file.suffix[1:]
                    + "=/*! KagNode. HTTP Boot | Source retained in project repository. */",
                    "--outfile=" + str(out),
                ],
                check=True,
                capture_output=True,
            )
            data = out.read_bytes()
            mime = (
                "text/css; charset=utf-8"
                if file.suffix == ".css"
                else "application/javascript; charset=utf-8"
            )
        name = (
            "/assets/"
            + file.stem
            + "."
            + hashlib.sha256(data).hexdigest()[:16]
            + file.suffix
        )
        names["/assets/" + file.name] = name
        assets[name] = (mime, data)
html = (source / "index.html").read_text()
for old, new in names.items():
    html = html.replace('"' + old + '"', '"' + new + '"')
html = re.sub(r">\s+<", "><", html)
output = (
    '# Generated by scripts/build-web.py; readable sources remain under web/.\nUI_VERSION = "5.0.0"\nHTML = '
    + repr(html)
    + "\nASSETS = "
    + repr(assets)
    + "\n"
)
(root / "httpboot/server_web_assets.py").write_text(output)
print(
    "Built", len(assets), "fingerprinted HTTP Boot console assets without source maps."
)
